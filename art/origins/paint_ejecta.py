"""Bake two translucent volcanic clouds into portable Roblox gradient bands.

Run from the project root with NumPy and SciPy. A row stores pairs of opacity
and shaded density nibbles. The Luau painter samples these in world-space UI,
so the original artwork ships with the place without a texture asset ID.
"""
from pathlib import Path

import numpy as np
from scipy.ndimage import gaussian_filter, map_coordinates

ROWS, COLS = 50, 33


def cloud(seed, flame):
    rng = np.random.default_rng(seed)
    res = 72
    y, x, z = np.mgrid[1:-1:complex(ROWS), -1:1:complex(COLS), -1:1:complex(res)]
    grid = np.stack((x, y, z))
    # Three bands of smooth noise curl the boundary and open cavities between lobes.
    lattices = [rng.random((28, 28, 28)) * 2 - 1 for _ in range(7)]

    def noise(axes, freq, n):
        return map_coordinates(lattices[n], (axes + 2.4) * freq + 2, order=2, mode="wrap")

    warped = grid.copy()
    for n in range(3):
        warped[n] += 0.15 * noise(grid, 2, n) + 0.065 * noise(grid, 6.7, n + 2)
    X, Y, Z = warped
    if flame:
        clumps = [
            (-.06,-.38, .03, .40,.49,.38), (.13,.03,.02,.46,.57,.41),
            (-.23,.23,.08,.36,.34,.36),(.27,.45,-.07,.32,.37,.32),
            (-.07,.61,.03,.30,.26,.29),(.52,.19,-.09,.20,.25,.24),
            (-.48,-.1,-.03,.22,.29,.23),(.30,-.28,.12,.29,.31,.24),
        ]
    else:
        clumps = [
            (-.28,-.12,.02,.40,.39,.44),(.15,-.11,.04,.49,.48,.47),
            (-.42,.14,-.02,.34,.27,.26),(-.07,.36,.06,.40,.27,.35),
            (.37,.2,.02,.35,.39,.36),(.60,-.14,.07,.22,.26,.33),
            (.02,-.45,.04,.37,.27,.31),
        ]
    field = np.full_like(x, -9.)
    for cx, cy, cz, a,b,c in clumps:
        surface = 1 - np.sqrt(((X-cx)/a)**2 + ((Y-cy)/b)**2 + ((Z-cz)/c)**2)
        field = np.maximum(field, surface)
    fine = noise(warped, 9.3, 6)
    fold = noise(warped, 3.2, 4) + .46 * noise(warped, 7.7, 3)
    density = np.clip((field + .10 + fine*.15) * 1.9,0,1)
    # The shock lights the inner cloud from its base. Above it, directional
    # skylight reveals the ridges of the gray ash that peels off the column.
    key = np.clip(.43 + .29*X + .36*Y + .30*fold + .16*fine,0,1)
    if flame:
        key = np.clip(.49 - .28*Y - .12*X + .50*fold + .14*fine + .30*np.maximum(0,field),0,1)
    transmit = np.ones((ROWS,COLS))
    light = np.zeros((ROWS,COLS))
    for i in range(res-1,-1,-1):
        alpha = 1-np.exp(-density[:,:,i]*(.26 if flame else .20))
        light += transmit * alpha * key[:,:,i]
        transmit *= 1-alpha
    opacity = np.clip(1-transmit,0,1)
    luminance = np.divide(light,opacity,out=np.zeros_like(opacity),where=opacity>.0001)
    # Smooth isolated subpixel specks before quantizing.
    alpha = np.rint(np.clip(gaussian_filter(opacity,.29),0,1)*15).astype(int)
    color = np.rint(np.clip(luminance,0,1)*15).astype(int)
    return ["".join(f"{a:x}{k:x}" for a,k in zip(ay,ky)) for ay,ky in zip(alpha,color)]


if __name__ == "__main__":
    target=Path("src/client/MineOrigins/EjectaPaint.luau")
    blocks=["-- Generated by art/origins/paint_ejecta.py; each pixel is opacity and shaded density.\nreturn {"]
    for name,seed,flame in [("melt",1971,True),("ash",6344,False)]:
        blocks.append("\t"+name+" = {")
        blocks.extend('\t\t"'+row+'",' for row in cloud(seed,flame))
        blocks.append("\t},")
    target.write_text("\n".join(blocks+["}",""]),encoding="utf8")
